# genloader.py vk.xml out.c: the static Vulkan loader of 9front.
#
# 9front has no shared libraries, so there is no loader that opens an
# ICD; the one driver is linked into the program (libvulkan.a).  This
# writes the part of the loader that depends on the registry: one
# trampoline per command (vkCmdDraw, vkCreateBuffer, ...) that calls
# the driver through the dispatch table the loader keeps in the first
# word of every dispatchable object (VK_LOADER_DATA, as the Khronos
# loader does), the table of names, and the slots.  The functions are
# vkl_CmdDraw etc.; vkCmdDraw is a weak alias.  vkloader.c holds
# the hand-written part: instance and device creation, proc addresses.
#
# Commands: those of the vulkan API (not vulkansc), core and every
# extension without a platform, or with platform plan9.

import sys
import xml.etree.ElementTree as ET

PLATFORMS = {'plan9'}
# written by hand in vkloader.c
HAND = {
	'vkGetInstanceProcAddr', 'vkGetDeviceProcAddr',
	'vkCreateInstance', 'vkDestroyInstance',
	'vkEnumeratePhysicalDevices', 'vkEnumeratePhysicalDeviceGroups',
	'vkEnumeratePhysicalDeviceGroupsKHR',
	'vkCreateDevice', 'vkDestroyDevice',
	'vkGetDeviceQueue', 'vkGetDeviceQueue2',
	'vkAllocateCommandBuffers',
}
GLOBAL = {'VkInstance': 'instance', 'VkPhysicalDevice': 'instance',
	'VkDevice': 'device', 'VkQueue': 'device', 'VkCommandBuffer': 'device'}

def isvulkan(e):
	api = e.get('api')
	return api is None or 'vulkan' in api.split(',')

def internal(n):
	return 'vkl_' + n[2:]

def text(e):
	s = ''.join(e.itertext())
	return ' '.join(s.split())

def main(xml, out):
	reg = ET.parse(xml).getroot()
	cmds = {}
	alias = {}
	for c in reg.find('commands').findall('command'):
		if not isvulkan(c):
			continue
		if c.get('alias'):
			alias[c.get('name')] = c.get('alias')
			continue
		proto = c.find('proto')
		name = proto.find('name').text
		params = [p for p in c.findall('param') if isvulkan(p)]
		cmds[name] = (proto.find('type').text, params)

	want = []
	def require(parent):
		for r in parent.findall('require'):
			if not isvulkan(r):
				continue
			for c in r.findall('command'):
				n = c.get('name')
				if n not in want:
					want.append(n)
	for f in reg.findall('feature'):
		if 'vulkan' in f.get('api').split(','):
			require(f)
	for x in reg.find('extensions').findall('extension'):
		if 'vulkan' not in x.get('supported').split(','):
			continue
		p = x.get('platform')
		if p is not None and p not in PLATFORMS:
			continue
		require(x)

	o = []
	w = o.append
	w('/* generated by genloader.py from vk.xml; do not edit */')
	w('#include "vkloader.h"')
	w('')
	names = []
	handalias = []
	for n in want:
		ret, params = cmds[alias.get(n, n)]
		names.append(n)
		first = params[0].find('type').text
		level = GLOBAL.get(first)
		decl = ', '.join(text(p) for p in params)
		args = ', '.join(p.find('name').text for p in params)
		idx = len(names) - 1
		# the public name, weak: a program may define its own vkCreateDevice
		# (a function pointer, as vkcube and vulkaninfo do), then the
		# loader keeps using its vkl_ function
		pub = 'VKAPI_ATTR %s VKAPI_CALL %s(%s) __attribute__((weak, alias("%s")));' % (ret, n, decl, internal(n))
		if n in HAND:
			w('VKAPI_ATTR %s VKAPI_CALL %s(%s);' % (ret, internal(n), decl))
			handalias.append(pub)
			continue
		w('VKAPI_ATTR %s VKAPI_CALL' % ret)
		w('%s(%s)' % (internal(n), decl))
		w('{')
		if level is None:
			call = '((PFN_%s)vkl_global(%d))(%s)' % (n, idx, args)
		else:
			call = '((PFN_%s)VKL_DISPATCH(%s)->fn[%d])(%s)' % (n, params[0].find('name').text, idx, args)
		w('\t%s%s;' % ('' if ret == 'void' else 'return ', call))
		w('}')
		w(pub)
		w('')
	w('const char *const vkl_names[VKL_NCMD] = {')
	for n in names:
		w('\t"%s",' % n)
	w('};')
	w('')
	# which table a command is looked up in: 0 global, 1 instance, 2 device
	w('const unsigned char vkl_level[VKL_NCMD] = {')
	for n in names:
		first = cmds[alias.get(n, n)][1][0].find('type').text
		w('\t%d,\t/* %s */' % ({None: 0, 'instance': 1, 'device': 2}[GLOBAL.get(first)], n))
	w('};')
	w('')
	w('/* sorted, for vkl_lookup */')
	w('const unsigned short vkl_sorted[VKL_NCMD] = {')
	for i in sorted(range(len(names)), key=lambda i: names[i]):
		w('\t%d,' % i)
	w('};')
	w('')
	w('PFN_vkVoidFunction const vkl_tramp[VKL_NCMD] = {')
	for n in names:
		w('\t(PFN_vkVoidFunction)%s,' % internal(n))
	w('};')
	src = '\n'.join(o) + '\n'
	hdr = '/* generated by genloader.py from vk.xml; do not edit */\n#define VKL_NCMD %d\n' % len(names)
	for n in sorted(HAND):
		hdr += '#define VKL_%s %d\n' % (n, names.index(n))
	# the public names of the commands of vkloader.c, expanded there
	hdr += '#define VKL_HAND_ALIASES \\\n' + ' \\\n'.join('\t' + a for a in handalias) + '\n'
	for path, s in ((out, src), (out.rsplit('.', 1)[0] + '.h', hdr)):
		try:
			if open(path).read() == s:
				continue
		except OSError:
			pass
		open(path, 'w').write(s)

if __name__ == '__main__':
	if len(sys.argv) != 3:
		sys.exit('usage: genloader.py vk.xml out.c')
	main(sys.argv[1], sys.argv[2])
