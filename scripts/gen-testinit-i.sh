#!/bin/sh
# Assemble scripts/testinit.S (minimal hand-written test initcode, see
# that file's own comment) into sys/src/9/port/initcode.i, the raw
# byte array sys/src/9/port/userinit.c's proc0() copies to UTZERO.
#
# Same technique as gen-rebootcode-i.sh/gen-apbootstrap-i.sh: assemble,
# link at a fixed address (irrelevant here since the code is fully
# %rip-relative, but gcc still wants one), objcopy out the raw .text
# bytes, wrap as a C array.
set -e

ROOT=${PLAN9:-$(git rev-parse --show-toplevel)}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

gcc -c -m64 -mno-red-zone -fno-pic -fno-pie \
    "$ROOT/scripts/testinit.S" -o "$TMP/testinit.o"

gcc -nostdlib -static -Wl,-Ttext=0x200000 -Wl,--entry=start -Wl,-N \
    -o "$TMP/testinit.elf" "$TMP/testinit.o"

objcopy -O binary --only-section=.text "$TMP/testinit.elf" "$TMP/testinit.bin"

python3 - "$TMP/testinit.bin" "$ROOT/sys/src/9/port/initcode.i" <<'PYEOF'
import sys
binpath, outpath = sys.argv[1], sys.argv[2]
data = open(binpath, 'rb').read()
lines = [
	"/*",
	" * Generated by scripts/gen-testinit-i.sh from testinit.S -- a",
	" * minimal hand-written test initcode, NOT the real Plan 9 boot",
	" * process. Do not hand-edit.",
	" */",
	"uchar initcode[] = {",
]
for i in range(0, len(data), 12):
	chunk = data[i:i+12]
	lines.append("\t" + ", ".join("0x%02x" % b for b in chunk) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF
