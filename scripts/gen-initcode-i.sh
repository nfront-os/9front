#!/bin/bash
# Build the kernel's initcode (sys/src/9/port/initcode.i) the way 9front's
# pc64 mkfile does -- initcode.out: init9.$O initcode.$O /$objtype/lib/libc.a,
# linked -R1 so text and data share the one page proc0() copies to UTZERO
# -- with the port toolchain: pc64/init9.S (GCC port of ../pc/init9.c),
# port/initcode.c and libc's system call stubs. proc0() starts it at
# UTZERO+0x28, past where the a.out header was, so the image is preceded
# by 0x28 bytes. Needs amd64/lib.gcc/libc.a (the build tool builds it first).
# objtype=386: pc/init9.c, 8l's 32-byte header, 386/lib.gcc/libc.a.
set -e
ROOT=${PLAN9:-$(git -C "$(dirname "$0")" rev-parse --show-toplevel)}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
OBJCOPY=objcopy
ENTRY=_main
case ${objtype:=amd64} in
amd64)
	UTZERO=0x200000
	HDR=0x28	# 6l's a.out header
	CC="gcc -mcmodel=small"
	LD=ld
	INIT9=pc64/init9.S
	;;
386)
	# 8l: pc/init9.c as it is (cdecl leaves argv0 on the stack as 8c
	# does), header of 32 bytes (touser: UTZERO+32)
	UTZERO=0x1000
	HDR=0x20
	CC="gcc -m32 -march=pentium -mno-sse"
	LD="ld -m elf_i386"
	INIT9=pc/init9.c
	;;
arm64)
	# 7l: header of 0x28 bytes, touser enters at UTZERO+0x28 (0x10028)
	UTZERO=0x10000
	HDR=0x28
	CC="aarch64-linux-musl-gcc -fsigned-char -mno-outline-atomics"	# as arm64/cflags.json
	LD=aarch64-linux-musl-ld
	OBJCOPY=aarch64-linux-musl-objcopy
	INIT9=arm64/init9.S
	ENTRY=main
	;;
*)
	echo "gen-initcode-i.sh: objtype=$objtype unknown" >&2
	exit 1
	;;
esac
CFLAGS="-std=gnu17 -fno-asm -ffreestanding -nostdinc -fno-builtin -fplan9-extensions
	-fno-omit-frame-pointer -fno-stack-protector -fno-pie -Os
	-I$ROOT/$objtype/include -I$ROOT/sys/include"
$CC $CFLAGS -c -o "$TMP/init9.o" "$ROOT/sys/src/9/$INIT9"
$CC $CFLAGS -c -o "$TMP/initcode.o" "$ROOT/sys/src/9/port/initcode.c"
# -N: text and data contiguous, like 8l -R1
$LD -N -static -Ttext=$(printf "%#x" $((UTZERO + HDR))) --entry=$ENTRY -o "$TMP/initcode.elf" \
	"$TMP/init9.o" "$TMP/initcode.o" "$ROOT/$objtype/lib.gcc/libc.a" \
	$( [ -f "$ROOT/$objtype/lib.gcc/libgcc.a" ] && echo "$ROOT/$objtype/lib.gcc/libgcc.a")
$OBJCOPY -O binary -R .bss -R .comment -R .note.gnu.property "$TMP/initcode.elf" "$TMP/initcode.bin"
python3 - "$TMP/initcode.bin" "$ROOT/sys/src/9/port/initcode.i" $HDR $INIT9 <<'PY'
import sys
data = bytes(int(sys.argv[3], 0)) + open(sys.argv[1], 'rb').read()
if len(data) > 4096:
	sys.exit('initcode: %d bytes, more than one page' % len(data))
out = ['/* generated by scripts/gen-initcode-i.sh from port/initcode.c, %s */' % sys.argv[4],
	'uchar initcode[] = {']
for i in range(0, len(data), 12):
	out.append('\t' + ', '.join('0x%02x' % b for b in data[i:i+12]) + ',')
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('initcode: %d bytes' % len(data))
PY
