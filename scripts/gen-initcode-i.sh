#!/bin/bash
# Build the kernel's initcode (sys/src/9/port/initcode.i) the way 9front's
# pc64 mkfile does -- initcode.out: init9.$O initcode.$O /$objtype/lib/libc.a,
# linked -R1 so text and data share the one page proc0() copies to UTZERO
# -- with the port toolchain: pc64/init9.S (GCC port of ../pc/init9.c),
# port/initcode.c and libc's system call stubs. proc0() starts it at
# UTZERO+0x28, past where the a.out header was, so the image is preceded
# by 0x28 bytes. Needs amd64/lib/libc.a (scripts/build-cli.sh).
set -e
ROOT=${PLAN9:-$(git -C "$(dirname "$0")" rev-parse --show-toplevel)}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
UTZERO=0x200000
CFLAGS="-std=gnu17 -fno-asm -ffreestanding -nostdinc -fno-builtin -fplan9-extensions
	-fno-omit-frame-pointer -fno-stack-protector -fno-pie -mcmodel=small -Os
	-I$ROOT/amd64/include -I$ROOT/sys/include"
gcc $CFLAGS -c -o "$TMP/init9.o" "$ROOT/sys/src/9/pc64/init9.S"
gcc $CFLAGS -c -o "$TMP/initcode.o" "$ROOT/sys/src/9/port/initcode.c"
# -N: text and data contiguous, like 8l -R1
ld -N -static -Ttext=$(printf "%#x" $((UTZERO + 0x28))) --entry=_main -o "$TMP/initcode.elf" \
	"$TMP/init9.o" "$TMP/initcode.o" "$ROOT/amd64/lib/libc.a"
objcopy -O binary -R .bss -R .comment -R .note.gnu.property "$TMP/initcode.elf" "$TMP/initcode.bin"
python3 - "$TMP/initcode.bin" "$ROOT/sys/src/9/port/initcode.i" <<'PY'
import sys
data = bytes(0x28) + open(sys.argv[1], 'rb').read()
if len(data) > 4096:
	sys.exit('initcode: %d bytes, more than one page' % len(data))
out = ['/* generated by scripts/gen-initcode-i.sh from port/initcode.c, pc64/init9.S */',
	'uchar initcode[] = {']
for i in range(0, len(data), 12):
	out.append('\t' + ', '.join('0x%02x' % b for b in data[i:i+12]) + ',')
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('initcode: %d bytes' % len(data))
PY
