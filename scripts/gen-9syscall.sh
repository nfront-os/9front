#!/bin/bash
# Generate libc's system call stubs (sys/src/libc/9syscall/*.S) from
# sys.h the way 9front's 9syscall/mkfile does: one stub per #define,
# named after the lower-cased entry; exits and nsec get a leading _, the
# stub for seek is called _seek (amd64/_seek.c wraps it).
#
# amd64 stub, GCC port: the kernel takes the call number in %rbp and the
# arguments from the user stack at 8(%rsp), 16(%rsp), ... (6c passed the
# first argument in RARG and the rest on the stack; the 6a stub only
# spilled RARG). Under System V all arguments arrive in registers, so
# each stub reserves its own frame and spills all six argument
# registers -- no per-call argument count is needed. forkret zeroes
# %rbx/%rbp/%r12/%r13 on return; they are callee-saved under System V,
# so the stub saves and restores them.
#   frame: 0 = %rbp, 8..48 = arguments, 56/64/72 = %rbx/%r12/%r13
#
# Deviation: notify's raw stub is _notify; amd64/notetramp.S provides
# notify() as a trampoline to System V note handlers.
#
# --ape: APE's stubs instead (sys/src/ape/lib/ap/syscall/genall: every
# sys.h entry not starting with _, named _<ENTRY>; the amd64 rule names
# _SEEK's stub __SEEK, amd64/_seek.c wraps it). Deviation as above:
# _NOTIFY's raw stub is __NOTIFY, ape/lib/ap/amd64/notify.S provides
# _NOTIFY.
#
# 386 stub: see below; seek's raw stub is _seek (APE: __SEEK), wrapped
# by 386/_seek.c as on amd64 (8c returned the vlong through the pointer).
#
# usage: [objtype=386] scripts/gen-9syscall.sh [--ape] [dir]
set -e
ROOT=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
APE=
if [ "$1" = --ape ]; then
	APE=1
	shift
fi
if [ -n "$APE" ]; then
	D=${1:-$ROOT/sys/src/ape/lib/ap/syscall}
else
	D=${1:-$ROOT/sys/src/libc/9syscall}
fi
SYSH=$ROOT/sys/src/libc/9syscall/sys.h
cd "$D"
# GAS .S, beside the 6a .s that 9syscall/mkfile generates on Plan 9;
# earlier versions of this script wrote .s
rm -f *.s *.S
if [ -n "$APE" ]; then
	SYS=$(sed '/^#define._/d; s/#define.\([A-Z0-9_]*\).*/\1/' $SYSH)
else
	SYS=$(sed '/^#define._X[123]/d; s/#define.\([A-Z0-9_]*\).*/\1/' $SYSH)
fi
for I in $SYS; do
	n=$(sed -n "/[ 	]$I[ 	]/s/.*	//p" $SYSH)
	if [ -n "$APE" ]; then
		i=_$I
		j=$i
		case $i in _SEEK) j=__SEEK ;; esac
		case ${objtype:-amd64}$i in amd64_NOTIFY|arm64_NOTIFY) j=__NOTIFY ;; esac	# the trampoline
	else
		i=$(echo $I | tr A-Z a-z)
		case $i in exits|nsec) i=_$i ;; esac
		j=$i
		case $i in seek) j=_seek ;; esac
		case ${objtype:-amd64}$i in amd64notify|arm64notify) j=_notify ;; esac	# the trampoline
	fi
	case ${objtype:-amd64} in
	386)
		# 8a stub: number in AX, INT $64, the arguments where cdecl
		# leaves them (4(SP) up); the kernel gives every register but
		# AX back. seek and _nsec store -1 through their first
		# argument on error, as 9syscall/mkfile's.
		{
		cat <<STUB
/* generated by scripts/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	movl	\$$n, %eax
	int	\$64
STUB
		case $I in
		SEEK|_NSEC|NSEC)
			cat <<STUB
	cmpl	\$-1, %eax
	jne	1f
	movl	4(%esp), %ecx
	movl	%eax, 0(%ecx)
	movl	%eax, 4(%ecx)
1:
STUB
			;;
		esac
		echo '	ret'
		} > $i.S
		;;
	amd64)
		cat > $i.S <<STUB
/* generated by scripts/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	subq	\$80, %rsp
	movq	%rbp, 0(%rsp)
	movq	%rbx, 56(%rsp)
	movq	%r12, 64(%rsp)
	movq	%r13, 72(%rsp)
	movq	%rdi, 8(%rsp)
	movq	%rsi, 16(%rsp)
	movq	%rdx, 24(%rsp)
	movq	%rcx, 32(%rsp)
	movq	%r8, 40(%rsp)
	movq	%r9, 48(%rsp)
	movq	\$$n, %rbp
	syscall
	movq	72(%rsp), %r13
	movq	64(%rsp), %r12
	movq	56(%rsp), %rbx
	movq	0(%rsp), %rbp
	addq	\$80, %rsp
	ret
STUB
		;;
	arm64)
		# 7a stub: number in R0, SVC, the arguments read from the user
		# stack at 8(SP) up (7c passed the first in R0 and spilled it to
		# 0(FP)); under AAPCS64 all arrive in x0-x5, so each stub spills
		# them into its own 16-byte aligned frame. The kernel saves only
		# R0, R17 and R26-R30 for a system call: its C code keeps x19-x25
		# (callee-saved), but a fork child returns through forkret with
		# the kernel's values in them, so the stub saves them itself.
		#   frame: 8..48 = arguments, 56..104 = x19-x25
		cat > $i.S <<STUB
/* generated by scripts/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	sub	sp, sp, #128
	stp	x0, x1, [sp, #8]
	stp	x2, x3, [sp, #24]
	stp	x4, x5, [sp, #40]
	stp	x19, x20, [sp, #56]
	stp	x21, x22, [sp, #72]
	stp	x23, x24, [sp, #88]
	str	x25, [sp, #104]
	mov	x0, #$n
	svc	#0
	ldp	x19, x20, [sp, #56]
	ldp	x21, x22, [sp, #72]
	ldp	x23, x24, [sp, #88]
	ldr	x25, [sp, #104]
	add	sp, sp, #128
	ret
STUB
		;;
	*)
		echo "gen-9syscall.sh: no stubs for objtype=$objtype" >&2
		exit 1
		;;
	esac
done
ls *.S | wc -l
