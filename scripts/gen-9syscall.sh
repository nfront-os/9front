#!/bin/bash
# Generate libc's system call stubs (sys/src/libc/9syscall/*.s) from
# sys.h the way 9front's 9syscall/mkfile does: one stub per #define,
# named after the lower-cased entry; exits and nsec get a leading _, the
# stub for seek is called _seek (amd64/_seek.c wraps it).
#
# amd64 stub, GCC port: the kernel takes the call number in %rbp and the
# arguments from the user stack at 8(%rsp), 16(%rsp), ... (6c passed the
# first argument in RARG and the rest on the stack; the 6a stub only
# spilled RARG). Under System V all arguments arrive in registers, so
# each stub reserves its own frame and spills all six argument
# registers -- no per-call argument count is needed. forkret zeroes
# %rbx/%rbp/%r12/%r13 on return; they are callee-saved under System V,
# so the stub saves and restores them.
#   frame: 0 = %rbp, 8..48 = arguments, 56/64/72 = %rbx/%r12/%r13
#
# Deviation: notify's raw stub is _notify; amd64/notetramp.S provides
# notify() as a trampoline to System V note handlers.
set -e
D=${1:-$(git -C "$(dirname "$0")" rev-parse --show-toplevel)/sys/src/libc/9syscall}
cd "$D"
rm -f *.s
SYS=$(sed '/^#define._X[123]/d; s/#define.\([A-Z0-9_]*\).*/\1/' sys.h)
for I in $SYS; do
	i=$(echo $I | tr A-Z a-z)
	n=$(sed -n "/[ 	]$I[ 	]/s/.*	//p" sys.h)
	case $i in exits|nsec) i=_$i ;; esac
	j=$i
	case $i in seek) j=_seek ;; notify) j=_notify ;; esac
	cat > $i.s <<STUB
/* generated by scripts/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	subq	\$80, %rsp
	movq	%rbp, 0(%rsp)
	movq	%rbx, 56(%rsp)
	movq	%r12, 64(%rsp)
	movq	%r13, 72(%rsp)
	movq	%rdi, 8(%rsp)
	movq	%rsi, 16(%rsp)
	movq	%rdx, 24(%rsp)
	movq	%rcx, 32(%rsp)
	movq	%r8, 40(%rsp)
	movq	%r9, 48(%rsp)
	movq	\$$n, %rbp
	syscall
	movq	72(%rsp), %r13
	movq	64(%rsp), %r12
	movq	56(%rsp), %rbx
	movq	0(%rsp), %rbp
	addq	\$80, %rsp
	ret
STUB
done
ls *.s | wc -l
