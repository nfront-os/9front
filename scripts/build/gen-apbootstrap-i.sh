#!/bin/sh
# Regenerate sys/src/9/pc64/apbootstrap.i from sys/src/9/pc64/apbootstrap.S.
#
# mp.c does `#include "apbootstrap.i"` and expects it to define
# `static uchar apbootstrap[]` holding the raw machine code of the AP
# (secondary CPU) real-mode bootstrap trampoline, linked at APBOOTSTRAP
# (KZERO+0x7000, see sys/src/9/pc64/mem.h) and stripped to just its .text
# bytes -- same approach as gen-rebootcode-i.sh, see that script for the
# full rationale.
#
# Usage: scripts/build/gen-apbootstrap-i.sh [pc64|pc]   (default pc64; from the
# repo root, or pass PLAN9=<root>).
set -e

ROOT=${PLAN9:-$(git rev-parse --show-toplevel)}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# pc (objtype 386): apbootstrap.S at its APBOOTSTRAP (pc/mem.h, pc/mkfile)
case ${1:-pc64} in
pc64)
	KDIR=$ROOT/sys/src/9/pc64
	APBOOTSTRAP=0xffffffff80007000
	CFLAGS="-m64 -mno-red-zone"
	LDFLAGS=
	;;
pc)
	KDIR=$ROOT/sys/src/9/pc
	APBOOTSTRAP=0xF0007000
	CFLAGS=-m32
	LDFLAGS=-m32
	;;
*)
	echo "usage: gen-apbootstrap-i.sh [pc64|pc]" >&2
	exit 1
	;;
esac

gcc -c -std=c11 $CFLAGS -fno-pic -fno-pie \
    -I "$KDIR" -I "$KDIR/../port" -I "$ROOT/sys/include" \
    "$KDIR/apbootstrap.S" -o "$TMP/apbootstrap.o"

gcc $LDFLAGS -nostdlib -static -Wl,-Ttext=$APBOOTSTRAP -Wl,--entry=apbootstrap -Wl,-N \
    -o "$TMP/apbootstrap.elf" "$TMP/apbootstrap.o"

objcopy -O binary --only-section=.text "$TMP/apbootstrap.elf" "$TMP/apbootstrap.bin"

python3 - "$TMP/apbootstrap.bin" "$KDIR/apbootstrap.i" <<'PYEOF'
import sys
binpath, outpath = sys.argv[1], sys.argv[2]
data = open(binpath, 'rb').read()
lines = [
	"/*",
	" * Generated by scripts/build/gen-apbootstrap-i.sh from apbootstrap.S,",
	" * linked at APBOOTSTRAP (KZERO+0x7000). Do not hand-edit.",
	" */",
	"static uchar apbootstrap[] = {",
]
for i in range(0, len(data), 12):
	chunk = data[i:i+12]
	lines.append("\t" + ", ".join("0x%02x" % b for b in chunk) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF
