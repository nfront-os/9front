#!/bin/sh
# Regenerate sys/src/9/pc/rebootcode.i from sys/src/9/pc/rebootcode.S.
# 386 counterpart of gen-rebootcode-i.sh (pc64) -- see that script for the
# full rationale; this is the same approach at -m32 / REBOOTADDR 0x11000
# (sys/src/9/pc/mem.h).
#
# Usage: run from the repo root (or pass PLAN9=<root>).
set -e

ROOT=${PLAN9:-$(git rev-parse --show-toplevel)}
PC=$ROOT/sys/src/9/pc
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

REBOOTADDR=0x11000

gcc -c -std=c11 -m32 -fno-pic -fno-pie \
    -I "$PC" -I "$PC/../port" -I "$ROOT/sys/include" \
    "$PC/rebootcode.S" -o "$TMP/rebootcode.o"

gcc -m32 -nostdlib -static -Wl,-Ttext=$REBOOTADDR -Wl,--entry=main -Wl,-N \
    -o "$TMP/rebootcode.elf" "$TMP/rebootcode.o"

objcopy -O binary --only-section=.text "$TMP/rebootcode.elf" "$TMP/rebootcode.bin"

python3 - "$TMP/rebootcode.bin" "$PC/rebootcode.i" <<'PYEOF'
import sys
binpath, outpath = sys.argv[1], sys.argv[2]
data = open(binpath, 'rb').read()
lines = [
	"/*",
	" * Generated by scripts/build/gen-rebootcode-pc-i.sh from rebootcode.S,",
	" * linked at REBOOTADDR (0x11000). Do not hand-edit.",
	" */",
	"static uchar rebootcode[] = {",
]
for i in range(0, len(data), 12):
	chunk = data[i:i+12]
	lines.append("\t" + ", ".join("0x%02x" % b for b in chunk) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF
