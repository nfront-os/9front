#!/bin/bash
# Generate libc's system call stubs (sys/src/libc/9syscall/*.S) from
# sys.h the way 9front's 9syscall/mkfile does: one stub per #define,
# named after the lower-cased entry; exits and nsec get a leading _, the
# stub for seek is called _seek (amd64/_seek.c wraps it).
#
# amd64 stub, GCC port: the kernel takes the call number in %rbp and the
# arguments from the user stack at 8(%rsp), 16(%rsp), ... (6c passed the
# first argument in RARG and the rest on the stack; the 6a stub only
# spilled RARG). Under System V all arguments arrive in registers, so
# each stub reserves its own frame and spills all six argument
# registers -- no per-call argument count is needed. forkret zeroes
# %rbx/%rbp/%r12/%r13 on return; they are callee-saved under System V,
# so the stub saves and restores them.
#   frame: 0 = %rbp, 8..48 = arguments, 56/64/72 = %rbx/%r12/%r13
#
# Deviation: notify's raw stub is _notify; amd64/notetramp.S provides
# notify() as a trampoline to System V note handlers.
#
# --ape: APE's stubs instead (sys/src/ape/lib/ap/syscall/genall: every
# sys.h entry not starting with _, named _<ENTRY>; the amd64 rule names
# _SEEK's stub __SEEK, amd64/_seek.c wraps it). Deviation as above:
# _NOTIFY's raw stub is __NOTIFY, ape/lib/ap/amd64/notify.S provides
# _NOTIFY.
#
# 386 stub: see below; seek's raw stub is _seek (APE: __SEEK), wrapped
# by 386/_seek.c as on amd64 (8c returned the vlong through the pointer).
#
# usage: [objtype=386|arm64|riscv64] scripts/build/gen-9syscall.sh [--ape] [dir]
set -e
ROOT=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
APE=
if [ "$1" = --ape ]; then
	APE=1
	shift
fi
if [ -n "$APE" ]; then
	D=${1:-$ROOT/sys/src/ape/lib/ap/syscall}
else
	D=${1:-$ROOT/sys/src/libc/9syscall}
fi
SYSH=$ROOT/sys/src/libc/9syscall/sys.h
cd "$D"
# GAS .S, beside the 6a .s that 9syscall/mkfile generates on Plan 9;
# earlier versions of this script wrote .s
rm -f *.s *.S
if [ -n "$APE" ]; then
	SYS=$(sed '/^#define._/d; s/#define.\([A-Z0-9_]*\).*/\1/' $SYSH)
else
	SYS=$(sed '/^#define._X[123]/d; s/#define.\([A-Z0-9_]*\).*/\1/' $SYSH)
fi
# riscv64: the sizes of a call's arguments, 4 (int, long, ulong) or
# 8 (pointers, vlong), from its prototype in libc.h (APE: the same calls)
sizes(){
	case ${1#_} in
	SYSR1|NSEC)	;;
	ERRSTR)		[ $1 = _ERRSTR ] && echo 8 || echo 8 4 ;;
	BIND)		echo 8 8 4 ;;
	CHDIR|EXEC|EXITS|BRK_|REMOVE|NOTIFY|SEGDETACH|WAIT|PIPE)
			[ ${1#_} = EXEC ] && echo 8 8 || echo 8 ;;
	CLOSE|ALARM|SLEEP|RFORK|NOTED)	echo 4 ;;
	DUP)		echo 4 4 ;;
	FSESSION)	echo 4 8 4 ;;
	FAUTH)		echo 4 8 ;;
	FSTAT)		[ $1 = _FSTAT ] && echo 4 8 || echo 4 8 4 ;;
	SEGBRK|RENDEZVOUS|UNMOUNT)	echo 8 8 ;;
	MOUNT)		[ $1 = _MOUNT ] && echo 4 8 4 8 || echo 4 4 8 4 8 ;;
	OPEN|AWAIT)	echo 8 4 ;;
	READ|WRITE)	echo 4 8 4 ;;
	OSEEK)		echo 4 4 4 ;;
	STAT|WSTAT)	[ $1 = _STAT -o $1 = _WSTAT ] && echo 8 8 || echo 8 8 4 ;;
	CREATE)		echo 8 4 4 ;;
	FD2PATH)	echo 4 8 4 ;;
	FWSTAT)		[ $1 = _FWSTAT ] && echo 4 8 || echo 4 8 4 ;;
	SEGATTACH)	echo 4 8 8 4 ;;
	SEGFREE|SEGFLUSH|SEMACQUIRE|SEMRELEASE|TSEMACQUIRE)	echo 8 4 ;;
	SEEK)		echo 8 4 8 4 ;;
	FVERSION)	echo 4 4 8 4 ;;
	PREAD|PWRITE)	echo 4 8 4 8 ;;
	*)		echo "gen-9syscall.sh: no argument sizes for $1" >&2; exit 1 ;;
	esac
}
for I in $SYS; do
	n=$(sed -n "/[ 	]$I[ 	]/s/.*	//p" $SYSH)
	if [ -n "$APE" ]; then
		i=_$I
		j=$i
		case $i in _SEEK) j=__SEEK ;; esac
		case ${objtype:-amd64}$i in amd64_NOTIFY|arm64_NOTIFY|riscv64_NOTIFY) j=__NOTIFY ;; esac	# the trampoline
	else
		i=$(echo $I | tr A-Z a-z)
		case $i in exits|nsec) i=_$i ;; esac
		j=$i
		case $i in seek) j=_seek ;; esac
		case ${objtype:-amd64}$i in amd64notify|arm64notify|riscv64notify) j=_notify ;; esac	# the trampoline
	fi
	case ${objtype:-amd64} in
	386)
		# 8a stub: number in AX, INT $64, the arguments where cdecl
		# leaves them (4(SP) up); the kernel gives every register but
		# AX back. seek and _nsec store -1 through their first
		# argument on error, as 9syscall/mkfile's.
		{
		cat <<STUB
/* generated by scripts/build/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	movl	\$$n, %eax
	int	\$64
STUB
		case $I in
		SEEK|_NSEC|NSEC)
			cat <<STUB
	cmpl	\$-1, %eax
	jne	1f
	movl	4(%esp), %ecx
	movl	%eax, 0(%ecx)
	movl	%eax, 4(%ecx)
1:
STUB
			;;
		esac
		echo '	ret'
		} > $i.S
		;;
	amd64)
		cat > $i.S <<STUB
/* generated by scripts/build/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	subq	\$80, %rsp
	movq	%rbp, 0(%rsp)
	movq	%rbx, 56(%rsp)
	movq	%r12, 64(%rsp)
	movq	%r13, 72(%rsp)
	movq	%rdi, 8(%rsp)
	movq	%rsi, 16(%rsp)
	movq	%rdx, 24(%rsp)
	movq	%rcx, 32(%rsp)
	movq	%r8, 40(%rsp)
	movq	%r9, 48(%rsp)
	movq	\$$n, %rbp
	syscall
	movq	72(%rsp), %r13
	movq	64(%rsp), %r12
	movq	56(%rsp), %rbx
	movq	0(%rsp), %rbp
	addq	\$80, %rsp
	ret
STUB
		;;
	arm64)
		# 7a stub: number in R0, SVC, the arguments read from the user
		# stack at 8(SP) up (7c passed the first in R0 and spilled it to
		# 0(FP)); under AAPCS64 all arrive in x0-x5, so each stub spills
		# them into its own 16-byte aligned frame. The kernel saves only
		# R0, R17 and R26-R30 for a system call: its C code keeps x19-x25
		# (callee-saved), but a fork child returns through forkret with
		# the kernel's values in them, so the stub saves them itself.
		#   frame: 8..48 = arguments, 56..104 = x19-x25
		cat > $i.S <<STUB
/* generated by scripts/build/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	sub	sp, sp, #128
	stp	x0, x1, [sp, #8]
	stp	x2, x3, [sp, #24]
	stp	x4, x5, [sp, #40]
	stp	x19, x20, [sp, #56]
	stp	x21, x22, [sp, #72]
	stp	x23, x24, [sp, #88]
	str	x25, [sp, #104]
	mov	x0, #$n
	svc	#0
	ldp	x19, x20, [sp, #56]
	ldp	x21, x22, [sp, #72]
	ldp	x23, x24, [sp, #88]
	ldr	x25, [sp, #104]
	add	sp, sp, #128
	ret
STUB
		;;
	riscv64)
		# ja stub: number in R8 (x8, s0), ECALL, the result in R8; the
		# kernel reads the arguments from the user stack at 8(sp) up as
		# jc lays them out: types of up to 4 bytes in 4 bytes, wider ones
		# 8-byte aligned (sys/src/9/riscv64/dat.h: ARG). Under the psABI
		# they arrive in a0-a5, so each stub stores them at jc's offsets
		# by the argument sizes of the call (sizes() below, from the
		# prototypes in libc.h). s0 is callee-saved: kept in the frame.
		#   frame: 8.. = arguments, 56 = s0
		off=0
		st=
		r=0
		for z in $(sizes $I); do
			if [ $z = 4 ]; then
				st="$st	sw	a$r, $((8 + off))(sp)
"
				off=$((off + 4))
			else
				off=$(( (off + 7) & ~7 ))
				st="$st	sd	a$r, $((8 + off))(sp)
"
				off=$((off + 8))
			fi
			r=$((r + 1))
		done
		cat > $i.S <<STUB
/* generated by scripts/build/gen-9syscall.sh from sys.h */
.globl	$j
$j:
	addi	sp, sp, -64
	sd	s0, 56(sp)
$st	li	s0, $n
	ecall
	mv	a0, s0
	ld	s0, 56(sp)
	addi	sp, sp, 64
	ret
STUB
		;;
	*)
		echo "gen-9syscall.sh: no stubs for objtype=$objtype" >&2
		exit 1
		;;
	esac
done
ls *.S | wc -l
