#!/bin/sh
# Regenerate sys/src/9/pc64/rebootcode.i from sys/src/9/pc64/rebootcode.S.
#
# main.c does `#include "rebootcode.i"` and expects it to define
# `static uchar rebootcode[]` holding the raw machine code of the
# standalone reboot trampoline, linked at REBOOTADDR (0x11000, see
# sys/src/9/pc64/mem.h) and stripped down to just its .text bytes.
#
# The original mkfile-era build did this via a Plan9 `$LD -T$REBOOTADDR`
# link + `dd -iseek 40` to strip the Plan9 a.out header. This script is
# the gcc/binutils equivalent: a normal ELF link at the same address,
# then objcopy to pull out the raw bytes.
#
# Usage: scripts/build/gen-rebootcode-i.sh [pc64|arm64|bcm64|riscv64]  (default pc64;
# from the repo root, or pass PLAN9=<root>).
set -e

ROOT=${PLAN9:-$(git rev-parse --show-toplevel)}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# arm64 (and bcm64): rebootcode.out: rebootcode.$O cache.v8.$O, linked
# -T0x40020000 (arm64/mkfile; bcm64: 0x1c00), raw (-H6)
case ${1:-pc64} in
pc64)
	KDIR=$ROOT/sys/src/9/pc64
	REBOOTADDR=0x11000
	CC="gcc -m64 -mno-red-zone"
	OBJCOPY=objcopy
	SRC="$KDIR/rebootcode.S"
	ENTRY=main
	;;
arm64|bcm64)
	KDIR=$ROOT/sys/src/9/$1
	REBOOTADDR=$([ $1 = arm64 ] && echo 0x40020000 || echo 0x1c00)
	CC=aarch64-linux-musl-gcc
	OBJCOPY=aarch64-linux-musl-objcopy
	SRC="$KDIR/rebootcode.S $ROOT/sys/src/9/arm64/cache.v8.S"
	ENTRY=_start
	;;
riscv64)
	# position independent, copied to a page of its own (main.c)
	KDIR=$ROOT/sys/src/9/riscv64
	REBOOTADDR=0
	CC="riscv64-linux-gnu-gcc -march=rv64imac_zicsr_zifencei -mabi=lp64"
	OBJCOPY=riscv64-linux-gnu-objcopy
	SRC="$KDIR/rebootcode.S"
	ENTRY=main
	;;
*)
	echo "usage: gen-rebootcode-i.sh [pc64|arm64|bcm64|riscv64]" >&2
	exit 1
	;;
esac

objs=
for s in $SRC; do
	o=$TMP/$(basename $s .S).o
	$CC -c -std=c11 -fno-pic -fno-pie \
	    -I "$KDIR" -I "$KDIR/../port" -I "$ROOT/sys/include" \
	    $s -o $o
	objs="$objs $o"
done

$CC -nostdlib -static -Wl,-Ttext=$REBOOTADDR -Wl,--entry=$ENTRY -Wl,-N \
    -o "$TMP/rebootcode.elf" $objs

$OBJCOPY -O binary --only-section=.text "$TMP/rebootcode.elf" "$TMP/rebootcode.bin"

python3 - "$TMP/rebootcode.bin" "$KDIR/rebootcode.i" $REBOOTADDR <<'PYEOF'
import sys
binpath, outpath = sys.argv[1], sys.argv[2]
data = open(binpath, 'rb').read()
lines = [
	"/*",
	" * Generated by scripts/build/gen-rebootcode-i.sh from rebootcode.S,",
	" * linked at REBOOTADDR (%s). Do not hand-edit." % sys.argv[3],
	" */",
	"static uchar rebootcode[] = {",
]
for i in range(0, len(data), 12):
	chunk = data[i:i+12]
	lines.append("\t" + ", ".join("0x%02x" % b for b in chunk) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF
