#!/bin/sh
# Regenerate sys/src/9/pc64/rebootcode.i from sys/src/9/pc64/rebootcode.S.
#
# main.c does `#include "rebootcode.i"` and expects it to define
# `static uchar rebootcode[]` holding the raw machine code of the
# standalone reboot trampoline, linked at REBOOTADDR (0x11000, see
# sys/src/9/pc64/mem.h) and stripped down to just its .text bytes.
#
# The original mkfile-era build did this via a Plan9 `$LD -T$REBOOTADDR`
# link + `dd -iseek 40` to strip the Plan9 a.out header. This script is
# the gcc/binutils equivalent: a normal ELF link at the same address,
# then objcopy to pull out the raw bytes.
#
# Usage: run from the repo root (or pass PLAN9=<root>).
set -e

ROOT=${PLAN9:-$(git rev-parse --show-toplevel)}
PC64=$ROOT/sys/src/9/pc64
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

REBOOTADDR=0x11000

gcc -c -std=c11 -m64 -mno-red-zone -fno-pic -fno-pie \
    -I "$PC64" -I "$PC64/../port" -I "$ROOT/sys/include" \
    "$PC64/rebootcode.S" -o "$TMP/rebootcode.o"

gcc -nostdlib -static -Wl,-Ttext=$REBOOTADDR -Wl,--entry=main -Wl,-N \
    -o "$TMP/rebootcode.elf" "$TMP/rebootcode.o"

objcopy -O binary --only-section=.text "$TMP/rebootcode.elf" "$TMP/rebootcode.bin"

python3 - "$TMP/rebootcode.bin" "$PC64/rebootcode.i" <<'PYEOF'
import sys
binpath, outpath = sys.argv[1], sys.argv[2]
data = open(binpath, 'rb').read()
lines = [
	"/*",
	" * Generated by scripts/gen-rebootcode-i.sh from rebootcode.S,",
	" * linked at REBOOTADDR (0x11000). Do not hand-edit.",
	" */",
	"static uchar rebootcode[] = {",
]
for i in range(0, len(data), 12):
	chunk = data[i:i+12]
	lines.append("\t" + ", ".join("0x%02x" % b for b in chunk) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF
