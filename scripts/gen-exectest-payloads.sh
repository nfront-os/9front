#!/bin/sh
# Build real-toolchain test executables and embed them as kernel byte
# arrays (sys/src/9/port/testelf.i, testgo.i, testinitreal.i) for the
# ELF64-loader exec test: a gcc-compiled static ELF64 binary (tests
# sysexecelf.c's ET_EXEC path with genuine multi-PT_LOAD program
# headers), a real `GOOS=plan9 GOARCH=amd64 go build` binary (tests the
# a.out path with a real compiler's output, not hand-assembled), and
# the real amd64/bin/init binary built against this port's own gcc-built
# libc/libauth/libbio (sys/src/cmd/init/build.json) -- this one must
# already exist (build it first) and exercises the full userspace
# syscall ABI, not just a throwaway test program.
#
# The gcc and Go ones are plain Plan9-syscall programs (no libc needed
# for the gcc one; the Go one uses the standard library, which on
# GOOS=plan9 talks directly to Plan9 syscalls). All three get embedded
# read-only into the bootstrap test process's address space by a
# kernel-side change to proc0() (see userinit.c) at fixed VAs, since
# there is no real filesystem yet to exec() them from normally -- the
# test process (scripts/boot/testinit.S) copies each one's bytes into a #g
# (devsegment) shared segment via a plain write loop and exec()s that.
set -e

ROOT=${PLAN9:-$(git rev-parse --show-toplevel)}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# --- gcc ELF64 test binary ---
gcc -c -m64 -mno-red-zone -fno-pic -fno-pie \
    "$ROOT/scripts/boot/hello_elf.S" -o "$TMP/hello_elf.o"
gcc -nostdlib -static -no-pie -Wl,--entry=_start \
    -o "$TMP/hello_elf" "$TMP/hello_elf.o"

# --- go plan9/amd64 test binary ---
GOOS=plan9 GOARCH=amd64 go build -ldflags="-s -w" \
    -o "$TMP/hello_go" "$ROOT/scripts/boot/hello_go.go"

python3 - "$TMP/hello_elf" "$ROOT/sys/src/9/port/testelf.i" testelf <<'PYEOF'
import sys
binpath, outpath, name = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(binpath, 'rb').read()
lines = [
	"/* Generated by scripts/gen-exectest-payloads.sh. Do not hand-edit. */",
	"uchar %s[] = {" % name,
]
for i in range(0, len(data), 12):
	lines.append("\t" + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF

python3 - "$TMP/hello_go" "$ROOT/sys/src/9/port/testgo.i" testgo <<'PYEOF'
import sys
binpath, outpath, name = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(binpath, 'rb').read()
lines = [
	"/* Generated by scripts/gen-exectest-payloads.sh. Do not hand-edit. */",
	"uchar %s[] = {" % name,
]
for i in range(0, len(data), 12):
	lines.append("\t" + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF

# --- real, libc-linked init binary (Phase 1/2 verification: exercises
# the full gcc-built userspace stack -- libc/libauth/libbio syscall ABI,
# not just a hand-assembled or stdlib-only test program) ---
python3 - "$ROOT/amd64/bin/init" "$ROOT/sys/src/9/port/testinitreal.i" testinitreal <<'PYEOF'
import sys
binpath, outpath, name = sys.argv[1], sys.argv[2], sys.argv[3]
