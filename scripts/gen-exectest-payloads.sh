lines.append("};")
open(outpath, "w").write("\n".join(lines) + "\n")
print("wrote %d bytes to %s" % (len(data), outpath))
PYEOF

# --- real rc shell binary (sys/src/cmd/rc/build.json): the actual
# minimal-CLI deliverable -- exec'd with "-i" to force interactive mode
# (Isatty(0) would otherwise fail since our console isn't bound at
# "/dev/cons") so it reads from and prompts on the serial console ---
python3 - "$ROOT/amd64/bin/rc" "$ROOT/sys/src/9/port/testrc.i" testrc <<'PYEOF'
