# --- netmount (scripts/boot/netmount.c, Phase 2.5): configures a static IP
# matching QEMU's default SLIRP network and mounts a host-side `ufs` 9P
# server at /mnt/ufs, so rc/rcmain can be exec'd/sourced from REAL
# files instead of #g/pipe test-harness tricks ---
python3 - "$ROOT/amd64/bin/netmount" "$ROOT/sys/src/9/port/testnetmount.i" testnetmount <<'PYEOF'
