#!/usr/bin/env python3
"""
Generate the amd64 libc manifests for the gcc build tool from 9front's
own mkfiles, so libc.a has exactly the members 9front's libc.a has:

  sys/src/libc/libc.json         9sys, fmt (OFILES), port (CFILES after
                                 reduce), ucd (OFILES), 9syscall stubs
  sys/src/libc/amd64/build.json  amd64 SFILES + CFILES

port/reduce: a port file is dropped when amd64/ provides the same
function (any extension), exactly like 9front's port/mkfile. The amd64
assembly is ported to GAS next to 9front's 6a source: foo.S beside
foo.s (as the kernel's l.S beside l.s); the gcc build takes the .S.

9syscall: one stub per sys.h entry, named as 9front's 9syscall/mkfile
names them (generated by scripts/gen-9syscall.sh as GAS .S, beside the
6a .s files the 9syscall/mkfile generates on Plan 9).

Deviations from 9front, each needed for the System V ABI:
  amd64/notetramp.S  notify() as a trampoline between the kernel's
                     note-handler call and a System V handler; the raw
                     stub is _notify (see the file)

usage: scripts/genlibc.py
"""
import json
import os
import re
import sys

import genclean

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
LIBC = os.path.join(ROOT, 'sys', 'src', 'libc')
ARCH = 'amd64'
EXTRA_ARCH = ['notetramp.S']

def mkvar(d, name):
	text = open(os.path.join(LIBC, d, 'mkfile')).read().replace('\\\n', ' ')
	m = re.search(r'^%s\s*=(.*)$' % name, text, re.M)
	return m.group(1).split() if m else []

def stem(f):
	return os.path.splitext(f)[0]

def exists(d, f):
	if not os.path.exists(os.path.join(LIBC, d, f)):
		sys.exit('libc/%s/%s missing' % (d, f))
	return '%s/%s' % (d, f)

def ofiles(d):
	return [exists(d, stem(o) + '.c') for o in mkvar(d, 'OFILES')]

def arch_files():
	files = []
	for f in mkvar(ARCH, 'SFILES') + mkvar(ARCH, 'CFILES'):
		# the GAS port (.S) first; the mkfile may name getcallerpc.c
		for ext in ('.S', os.path.splitext(f)[1], '.s', '.c'):
			if os.path.exists(os.path.join(LIBC, ARCH, stem(f) + ext)):
				files.append('$ARCH/' + stem(f) + ext)
				break
		else:
			sys.exit('libc/%s/%s missing' % (ARCH, f))
	return files + ['$ARCH/' + f for f in EXTRA_ARCH]

def port_files(arch):
	archstems = {stem(os.path.basename(f)) for f in arch}
	return [exists('port', c) for c in mkvar('port', 'CFILES')
		if stem(c) not in archstems]

def syscall_files():
	# same names as 9syscall/mkfile and scripts/gen-9syscall.sh
	files = []
	for line in open(os.path.join(LIBC, '9syscall', 'sys.h')):
		m = re.match(r'#define\s+([A-Z0-9_]+)\s', line)
		if m is None or re.match(r'_X[123]', m.group(1)):
			continue
		i = m.group(1).lower()
		if i in ('exits', 'nsec'):
			i = '_' + i
		files.append('9syscall/%s.S' % i)
	return files

def main():
	arch = arch_files()
	src = ofiles('9sys') + syscall_files() + ofiles('fmt') + port_files(arch) + ofiles('ucd')
	libc = [{
		'Name': 'Libc',
		'Cflags': ['-fasm'],
		'Include': ['../lib.json', '$ARCH/build.json'],
		'Install': '/$ARCH/lib.gcc/',	# gcc archives; /$ARCH/lib is the native (6c) one
		'Library': 'libc.a',
		'Projects': ['9syscall/9syscall.json'],
		'Pre': ['bash ../../../scripts/gen-runetype.sh'],
		'Clean': genclean.clean(['bash ../../../scripts/gen-runetype.sh'], LIBC),
		'SourceFiles': src,
	}]
	archjson = [{'Name': 'archfiles', 'SourceFiles': arch}]
	for path, data in (('libc.json', libc), (ARCH + '/build.json', archjson)):
		open(os.path.join(LIBC, path), 'w').write(json.dumps(data, indent='\t') + '\n')
		print('sys/src/libc/%s: %d files' % (path, len(data[0]['SourceFiles'])))

main()
